"""Run every query in sql/ against data/ae.duckdb.

Writes each result to outputs/<query>.csv and a readable summary to outputs/sql_results.md.

Usage:
    python src/run_queries.py
"""

from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "sql"
OUT = ROOT / "outputs" / "sql_results.md"


MAX_ROWS = 15


def fmt(value, column: str) -> str:
    if value is None:
        return ""
    if isinstance(value, float) and value.is_integer() and "pct" not in column:
        value = int(value)
    if isinstance(value, int) and "year" not in column:
        return f"{value:,}"
    return str(value)


def to_markdown(df) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    shown = df if len(df) <= 2 * MAX_ROWS else None
    if shown is None:
        top, bottom = df.head(MAX_ROWS), df.tail(MAX_ROWS)
        rows = list(top.itertuples(index=False)) + [None] + list(bottom.itertuples(index=False))
    else:
        rows = list(shown.itertuples(index=False))
    for row in rows:
        if row is None:
            lines.append("| " + " | ".join(["..."] * len(cols)) + " |")
            continue
        lines.append("| " + " | ".join(fmt(v, c) for v, c in zip(row, cols)) + " |")
    if shown is None:
        lines.append(f"\n_{len(df)} rows; first and last {MAX_ROWS} shown. Full results in the CSV._")
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    con = duckdb.connect(str(ROOT / "data" / "ae.duckdb"))
    parts = ["# SQL results\n", "Generated by `src/run_queries.py`. Do not edit by hand.\n"]
    for path in sorted(SQL_DIR.glob("*.sql")):
        sql = path.read_text()
        result = con.execute(sql)
        if path.name.startswith("00_"):  # view definition, no results
            continue
        df = result.df()
        df.to_csv(OUT.parent / f"{path.stem}.csv", index=False)
        title = next((l[3:].strip() for l in sql.splitlines() if l.startswith("-- Q")), path.stem)
        parts.append(f"## {title}\n\nQuery: [`sql/{path.name}`](../sql/{path.name})\n\n{to_markdown(df)}\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
